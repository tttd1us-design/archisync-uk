export const findGlossaryMatches = (text) => {
  if (!text) return [];
  const found = [];
  const lowerText = text.toLowerCase();
  
  ARCHITECTURE_GLOSSARY.forEach((item) => {
    const termLower = item.term.toLowerCase().split(' (')[0];
    if (lowerText.includes(termLower)) {
      found.push(item);
    }
  });
  return found;
};